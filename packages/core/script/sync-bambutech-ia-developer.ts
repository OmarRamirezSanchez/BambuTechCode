#!/usr/bin/env bun

/**
 * Refreshes the BambuTech IA Developer plugin that BambuTechCode installs by default.
 *
 * Usage: bun run sync:bambutech-ia-developer <path to plugins/bambutech-ia-developer>
 *
 * The plugin is embedded in the CLI as one brotli-compressed, base64-encoded text file so the Bun executable, the
 * Node build and source runs all carry it without asset handling. Review the source checkout before syncing: every
 * file under the plugin directory ships to every installation.
 */

import { $ } from "bun"
import { createHash } from "node:crypto"
import { readdir } from "node:fs/promises"
import path from "node:path"
import { brotliCompressSync, constants } from "node:zlib"

const source = Bun.argv[2]
if (!source || source === "--help") {
  console.log("Usage: bun run sync:bambutech-ia-developer <path to plugins/bambutech-ia-developer>")
  process.exit(source ? 0 : 1)
}

const root = path.resolve(source)
const manifest = await Bun.file(path.join(root, ".claude-plugin", "plugin.json")).json()
if (manifest.name !== "bambutech-ia-developer") throw new Error(`Not the BambuTech IA Developer plugin: ${root}`)

// Bytecode caches are build output of the source checkout, not plugin content.
const keys = (await readdir(root, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile())
  .map((entry) => path.relative(root, path.join(entry.parentPath, entry.name)).replaceAll(path.sep, "/"))
  .filter((key) => !key.split("/").includes("__pycache__") && !key.endsWith(".pyc") && !key.endsWith(".DS_Store"))
  .toSorted()

const files = Object.fromEntries(
  await Promise.all(
    keys.map(async (key) => {
      const bytes = await Bun.file(path.join(root, key)).bytes()
      const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes)
      return [key, text] as const
    }),
  ),
)

const json = Buffer.from(JSON.stringify({ version: manifest.version, files }))
const bundle = brotliCompressSync(json, {
  params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: json.length },
}).toString("base64")

const git = await $`git -C ${root} rev-parse HEAD`.quiet().nothrow()
const dirty = await $`git -C ${root} status --porcelain -- .`.quiet().nothrow()
const target = path.resolve(import.meta.dirname, "../src/plugin/bambutech-ia-developer")
await Bun.write(path.join(target, "bundle.txt"), bundle)
const metadata = {
  name: manifest.name,
  version: manifest.version,
  revision: git.exitCode === 0 ? git.text().trim() : null,
  dirty: dirty.exitCode === 0 ? dirty.text().trim() !== "" : null,
  files: keys.length,
  sha256: createHash("sha256").update(bundle).digest("hex"),
}
await Bun.write(
  path.join(target, "source.ts"),
  [
    "// Generated by script/sync-bambutech-ia-developer.ts. Do not edit.",
    "export default {",
    ...Object.entries(metadata).map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`),
    "} as const",
    "",
  ].join("\n"),
)
console.log(
  `Synced ${manifest.name} ${manifest.version}: ${keys.length} files, ${(bundle.length / 1024 / 1024).toFixed(1)} MB embedded. Review the change before committing.`,
)
